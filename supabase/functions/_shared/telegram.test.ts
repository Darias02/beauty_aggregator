// Run offline with Node.js >= 22.18: node --test supabase/functions/_shared/telegram.test.ts
// Or with Deno: deno test --no-check supabase/functions/_shared/telegram.test.ts
import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
import { test as registerTest } from 'node:test';
import { INIT_DATA_MAX_AGE_SECONDS, validateInitData } from './telegram.ts';

const TOKEN = '123456:BB06_TEST_TOKEN'; // Deliberately fake; no real secrets or API calls.
const NOW = 1800000000;
const USER = {
    id: 424242424242,
    first_name: 'Дарья + &=',
    username: 'test_user',
    allows_write_to_pm: true
};

function fields(overrides: Record<string, string> = {}): URLSearchParams {
    return new URLSearchParams({
        query_id: 'AAE_test',
        auth_date: String(NOW),
        user: JSON.stringify(USER),
        start_param: 'booking_42',
        signature: 'test_signature',
        ...overrides
    });
}

// Independent signer: Node createHmac rather than the verifier's Web Crypto API.
function signed(params = fields(), token = TOKEN): string {
    const lines = [...params].filter(([key]) => key !== 'hash')
        .map(([key, value]) => `${key}=${value}`).sort();
    const secret = createHmac('sha256', 'WebAppData').update(token).digest();
    params.set('hash', createHmac('sha256', secret).update(lines.join('\n')).digest('hex'));
    return params.toString();
}

// Freeze time per sequential test without runner-specific mocking dependencies.
function test(name: string, run: () => Promise<void>) {
    registerTest(name, async () => {
        const originalNow = Date.now;
        Date.now = () => NOW * 1000;
        try {
            await run();
        } finally {
            Date.now = originalNow;
        }
    });
}

test('accepts an independent fixed HMAC vector and preserves the notification actor.id contract', async () => {
    // Cross-checked with Python stdlib hmac/hashlib, not generated by signed().
    const vector = fields();
    vector.set('hash', 'd34f9c95b078578ab619e016be40f853357e788abfbd08d0aa335199284c31dc');
    const actor = await validateInitData(vector.toString(), TOKEN);
    assert.deepEqual(actor, USER);
    assert.equal(actor?.id, USER.id);
    assert.equal(typeof actor?.id, 'number');
});

test('accepts required fields alone, reordered fields and URL encoding variants', async () => {
    const minimal = fields();
    for (const key of ['query_id', 'start_param', 'signature']) minimal.delete(key);
    assert.deepEqual(await validateInitData(signed(minimal), TOKEN), USER);
    const reordered = new URLSearchParams([...new URLSearchParams(signed())].reverse());
    assert.deepEqual(await validateInitData(reordered.toString().replace(/\+/g, '%20'), TOKEN), USER);
});

test('rejects tampering with users, optional fields, hashes and bot tokens', async () => {
    const original = signed();
    for (const [key, value] of [
        ['user', JSON.stringify({ ...USER, id: 999 })],
        ['start_param', 'another_booking'],
        ['signature', 'replaced_signature'],
        ['extra', 'unsigned_field']
    ]) {
        const forged = new URLSearchParams(original);
        forged.set(key, value);
        assert.equal(await validateInitData(forged.toString(), TOKEN), null, key);
    }
    const hash = new URLSearchParams(original).get('hash')!;
    for (const position of [0, 31, 63]) {
        const forged = new URLSearchParams(original);
        forged.set('hash', hash.slice(0, position) + (hash[position] === '0' ? '1' : '0') + hash.slice(position + 1));
        assert.equal(await validateInitData(forged.toString(), TOKEN), null);
    }
    assert.equal(await validateInitData(original, 'another:BOT_TOKEN'), null);
});

test('rejects non-string initDataUnsafe objects and client-supplied Telegram IDs', async () => {
    for (const input of [undefined, null, '', 424242424242, USER, { user: USER },
        { initDataUnsafe: { user: USER }, actor_id: USER.id }, { init_data: signed() },
        [signed()], String(USER.id), JSON.stringify({ actor_id: USER.id })]) {
        assert.equal(await validateInitData(input, TOKEN), null);
    }
    assert.equal(await validateInitData(signed(), ''), null);
});

test('requires nonempty hash, auth_date and user even on correctly signed data', async () => {
    for (const key of ['hash', 'auth_date', 'user']) {
        for (const missing of [true, false]) {
            const params = fields();
            if (missing) params.delete(key);
            else params.set(key, '');
            const input = new URLSearchParams(signed(params));
            if (key === 'hash') {
                if (missing) input.delete(key);
                else input.set(key, '');
            }
            assert.equal(await validateInitData(input.toString(), TOKEN), null, key);
        }
    }
});

test('requires a 64-character lowercase hexadecimal SHA-256 hash', async () => {
    for (const hash of ['0'.repeat(63), '0'.repeat(65), 'g'.repeat(64), 'A'.repeat(64),
        ' ' + '0'.repeat(64), '0'.repeat(64) + '\n', '0'.repeat(64)]) {
        const params = new URLSearchParams(signed());
        params.set('hash', hash);
        assert.equal(await validateInitData(params.toString(), TOKEN), null);
    }
});

test('rejects duplicate parameters including decoded aliases and unknown fields', async () => {
    for (const key of ['hash', 'auth_date', 'user', 'query_id', 'signature', 'extra']) {
        const params = fields({ extra: 'value' });
        params.append(key, params.get(key) || '0'.repeat(64));
        const input = signed(params);
        // signed() replaces hash, so add its duplicate explicitly for that case.
        const duplicated = key === 'hash' ? input + '&hash=' + new URLSearchParams(input).get('hash') : input;
        assert.equal(await validateInitData(duplicated, TOKEN), null, key);
        if (key === 'user') {
            assert.equal(await validateInitData(duplicated.replace('&user=', '&%75ser='), TOKEN), null);
        }
    }
});

test('rejects malformed query encoding and ambiguous signed key=value lines', async () => {
    for (const [key, value] of [['', 'empty_key'], ['bad\nkey', 'value'], ['bad=key', 'value'],
        ['extra', 'value\nuser=forged'], ['extra', 'value\r']]) {
        assert.equal(await validateInitData(signed(fields({ [key]: value })), TOKEN), null);
    }
    for (const value of ['%ZZ', '%', '%FF']) {
        const input = signed(fields({ extra: value })).replace(encodeURIComponent(value), value);
        assert.equal(await validateInitData(input, TOKEN), null, value);
    }
    const input = signed(fields({ extra: '' })).replace('extra=', 'extra');
    assert.equal(await validateInitData(input, TOKEN), null);
});

test('requires a positive safe integer Unix auth_date in decimal seconds', async () => {
    for (const auth_date of ['0', '-1', 'NaN', 'Infinity', '1.8e9', '1800000000.0',
        ' 1800000000', '+1800000000', '01800000000', '0x6b49d200', '9007199254740992',
        String(NOW * 1000), '1800000000\n']) {
        assert.equal(await validateInitData(signed(fields({ auth_date })), TOKEN), null, auth_date);
    }
});

test('preserves the 24-hour TTL boundary and rejects expired or future data', async () => {
    assert.equal(INIT_DATA_MAX_AGE_SECONDS, 86400);
    for (const age of [0, 1, 86399, 86400]) {
        assert.deepEqual(await validateInitData(signed(fields({ auth_date: String(NOW - age) })), TOKEN), USER);
    }
    for (const age of [86401, -1, -60, -86400]) {
        assert.equal(await validateInitData(signed(fields({ auth_date: String(NOW - age) })), TOKEN), null, String(age));
    }
    Date.now = () => NOW * 1000 + 1;
    assert.equal(await validateInitData(signed(fields({ auth_date: String(NOW - 86400) })), TOKEN), null);
});

test('allows explicit server TTL policy without changing the notification default', async () => {
    const input = signed(fields({ auth_date: String(NOW - 3601) }));
    assert.equal(await validateInitData(input, TOKEN, { maxAgeSeconds: 3600 }), null);
    assert.deepEqual(await validateInitData(input, TOKEN), USER);
    assert.deepEqual(await validateInitData(signed(fields({ auth_date: String(NOW - 3600) })),
        TOKEN, { maxAgeSeconds: 3600 }), USER);
    for (const maxAgeSeconds of [NaN, Infinity, -1, 0, 0.5]) {
        assert.equal(await validateInitData(signed(), TOKEN, { maxAgeSeconds }), null);
    }
});

test('validates user JSON, object shape, numeric ID and known field types', async () => {
    const invalidUsers = ['{', 'null', '[]', 'true', '42', '"user"',
        ...[{}, { id: USER.id }, { ...USER, first_name: null }, { ...USER, id: '424242424242' },
            ...[0, -1, 1.5, 9007199254740992, null].map((id) => ({ ...USER, id })),
            { ...USER, username: false }, { ...USER, photo_url: {} },
            { ...USER, is_premium: 'true' }, { ...USER, allows_write_to_pm: 1 }].map((value) => JSON.stringify(value))];
    for (const user of invalidUsers) {
        assert.equal(await validateInitData(signed(fields({ user })), TOKEN), null, user);
    }
    const extended = { ...USER, id: 2 ** 52 - 1, first_name: '', future_telegram_field: 'allowed' };
    assert.deepEqual(await validateInitData(signed(fields({ user: JSON.stringify(extended) })), TOKEN), extended);
});
