-- Starting point for NEW, empty test installations only. Never replay against
-- an existing database. auth/storage and Supabase roles belong to the platform.
-- Reconstructed from tests/bb24/schema.sql metadata and server repositories.
-- Columns added by 20260930_bb.sql deliberately remain in that migration.
begin;

create table public.users (
    user_id bigint primary key,
    name text not null,
    phone_number text
);

create table public.masters (
    master_id bigint primary key,
    name text not null,
    phone_number text
);

create table public.services (
    service_id bigint generated by default as identity primary key,
    name text not null,
    description text
);

create table public.slots (
    slot_id bigint generated by default as identity primary key,
    date_time timestamptz not null,
    status text default 'available',
    master_id bigint references public.masters(master_id) on delete cascade,
    service_id bigint references public.services(service_id) on delete cascade
);

create table public.bookings (
    booking_id bigint generated by default as identity primary key,
    user_id bigint references public.users(user_id) on delete cascade,
    slot_id bigint references public.slots(slot_id) on delete cascade,
    status text default 'confirmed'
);

-- Supabase default ACLs can grant newly created objects to client roles.
-- Revoke explicitly; no broad fixture grants or default-privilege changes.
revoke all on public.users, public.masters, public.services, public.slots,
    public.bookings from public, anon, authenticated;
revoke all on sequence public.services_service_id_seq, public.slots_slot_id_seq,
    public.bookings_booking_id_seq from public, anon, authenticated;
grant usage on schema public to service_role;
grant select, insert, update, delete on public.users, public.masters,
    public.services, public.slots, public.bookings to service_role;
grant usage on sequence public.services_service_id_seq, public.slots_slot_id_seq,
    public.bookings_booking_id_seq to service_role;

-- No policies: BB-01 expects none and rechecks server CRUD/sequence access.
alter table public.users enable row level security;
alter table public.masters enable row level security;
alter table public.services enable row level security;
alter table public.slots enable row level security;
alter table public.bookings enable row level security;

commit;
