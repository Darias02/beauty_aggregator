"""Prepare reviewed SQL + synthetic production-shape fixture. Never connects to a DB.

python3 scripts/prepare_existing_upgrade.py
Output is a NEW /private/tmp directory. No CLI push/reset/repair/deploy is invoked.
"""
import hashlib
import json
from pathlib import Path
import tempfile

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / 'tests/bb73/schema_fixture.json'
TABLES = ['users', 'masters', 'services', 'slots', 'bookings']
SELECTED = [
    '20261029202351_bb01_restrict_public_core_tables.sql',
    '20261030153951_bb03_lock_master_avatar_writes.sql',
    '20261030181231_telegram_webhook_updates.sql',
    '20261030191314_bb24_atomic_booking.sql',
    '20261101140000_bb63_slots_write.sql',
    '20261101150000_bb64_slot_cancel.sql',
    '20261101160000_bb66_booking_decisions.sql',
    '20261101170000_bb67_model_cancel.sql',
    '20261108184749_bb73_preserve_booking_history.sql',
    '20261113135354_bb73_preserve_parent_history.sql',
]


def quote(identifier):
    if not identifier.replace('_', '').isalnum():
        raise ValueError('Unexpected identifier in reviewed evidence')
    return '"' + identifier + '"'


def prepare(*, output_parent=Path('/private/tmp')):
    catalog = json.loads(EVIDENCE.read_text())
    if catalog['functions'] or catalog['history_relation'] is not None:
        raise ValueError('Snapshot does not match the reviewed pre-upgrade state')
    directory = Path(tempfile.mkdtemp(prefix='bb73-existing-upgrade-', dir=output_parent))
    fixture = ['-- LOCAL SYNTHETIC FIXTURE ONLY. Not a production migration.']
    expected = {}
    for table in TABLES:
        columns = [c for c in catalog['columns'] if c['relname'] == table]
        if not columns:
            raise ValueError('Missing reviewed table')
        definitions = []
        expected[table] = []
        for c in columns:
            if c['type'] not in ('bigint', 'text', 'timestamp with time zone'):
                raise ValueError('Unexpected type in reviewed evidence')
            line = quote(c['attname']) + ' ' + c['type']
            if c['attidentity'] == 'd':
                line += ' generated by default as identity'
            if c['default_expression']:
                if c['default_expression'] not in ("'confirmed'::text", "'available'::text"):
                    raise ValueError('Unexpected default expression')
                line += ' default ' + c['default_expression']
            if c['attnotnull']:
                line += ' not null'
            definitions.append(line)
            expected[table].append({'name': c['attname'], 'type': c['type'],
                'notnull': c['attnotnull'], 'identity': c['attidentity'], 'default': c['default_expression']})
        fixture.append(f'create table public.{quote(table)} (' + ','.join(definitions) + ');')
    for c in sorted(catalog['constraints'], key=lambda c: c['contype'] != 'p'):
        if c['contype'] not in ('p', 'f') or ';' in c['definition']:
            raise ValueError('Unexpected constraint')
        fixture.append(f'alter table public.{quote(c["relation"])} add constraint {quote(c["conname"])} {c["definition"]};')
    for i in catalog['indexes']:
        if not i['index_name'].endswith('_pkey'):
            if ';' in i['definition'] or not i['definition'].startswith('CREATE '):
                raise ValueError('Unexpected index')
            fixture.append(i['definition'] + ';')
    fixture += [
        'grant all on public.users,public.masters,public.services,public.slots,public.bookings to anon,authenticated,service_role;',
        'grant all on sequence public.services_service_id_seq,public.slots_slot_id_seq,public.bookings_booking_id_seq to anon,authenticated,service_role;',
        'alter default privileges in schema public grant all on tables to anon,authenticated,service_role;',
        'alter default privileges in schema public grant all on sequences to anon,authenticated,service_role;',
        'alter default privileges in schema public grant execute on functions to anon,authenticated,service_role;',
    ]
    # Reproduce the three audited Storage policies/settings only in local Supabase.
    old = (ROOT / 'supabase/migrations/20260930_bb.sql').read_text()
    fixture.append(old[old.index('insert into storage.buckets'):])
    (directory / 'local-fixture.sql').write_text('\n'.join(fixture) + '\n')
    preflight = """-- Approved existing-database route only. Aborts on shape/security drift.
do $preflight$
declare target record; actual jsonb;
begin
    if to_regclass('supabase_migrations.schema_migrations') is not null then
        raise exception 'BB-73: migration history appeared; review before execution';
    end if;
    if exists(select 1 from pg_proc where pronamespace='public'::regnamespace) then
        raise exception 'BB-73: public function drift';
    end if;
    if exists(select 1 from pg_policy where polrelid in
        ('public.users'::regclass,'public.masters'::regclass,'public.services'::regclass,'public.slots'::regclass,'public.bookings'::regclass)) then
        raise exception 'BB-73: core policy drift';
    end if;
    if exists(select 1 from pg_trigger where not tgisinternal and tgrelid in
        ('public.users'::regclass,'public.masters'::regclass,'public.services'::regclass,'public.slots'::regclass,'public.bookings'::regclass)) then
        raise exception 'BB-73: core trigger drift';
    end if;
    if exists(select 1 from pg_class where relnamespace='public'::regnamespace and relkind in ('v','m')) then
        raise exception 'BB-73: public view drift';
    end if;
    for target in select key as name, value as columns from jsonb_each(EXPECTED::jsonb) loop
        select jsonb_agg(jsonb_build_object('name',a.attname,'type',format_type(a.atttypid,a.atttypmod),
            'notnull',a.attnotnull,'identity',a.attidentity,'default',pg_get_expr(d.adbin,d.adrelid)) order by a.attnum)
        into actual from pg_attribute a left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
        where a.attrelid=format('public.%I',target.name)::regclass and a.attnum>0 and not a.attisdropped;
        if actual is distinct from target.columns then
            raise exception 'BB-73: column drift on %',target.name;
        end if;
    end loop;
    for target in select * from jsonb_each_text(INDEXES::jsonb) loop
        if (select pg_get_indexdef(c.oid) from pg_class c
            where c.relnamespace='public'::regnamespace and c.relname=target.key)
            is distinct from target.value then
            raise exception 'BB-73: index drift on %',target.key;
        end if;
    end loop;
    select jsonb_object_agg(conname,replace(pg_get_constraintdef(oid),'public.',''))
    into actual from pg_constraint where conrelid in
        ('public.users'::regclass,'public.masters'::regclass,'public.services'::regclass,'public.slots'::regclass,'public.bookings'::regclass);
    if actual is distinct from CONSTRAINTS::jsonb then
        raise exception 'BB-73: constraint drift';
    end if;
    if not exists(select 1 from storage.buckets where id='master-avatars' and public
        and file_size_limit is null and allowed_mime_types is null) then
        raise exception 'BB-73: bucket drift';
    end if;
end;
$preflight$;
""".replace('EXPECTED', "'" + json.dumps(expected).replace("'", "''") + "'")
    indexes = {i['index_name']: i['definition'] for i in catalog['indexes']}
    preflight = preflight.replace('INDEXES', "'" + json.dumps(indexes).replace("'", "''") + "'")
    constraints = {c['conname']: c['definition'].replace('public.', '') for c in catalog['constraints']}
    preflight = preflight.replace('CONSTRAINTS', "'" + json.dumps(constraints).replace("'", "''") + "'")
    (directory / '00_preflight.sql').write_text(preflight)
    hashes = {'00_preflight.sql': hashlib.sha256(preflight.encode()).hexdigest()}
    (directory / 'migrations').mkdir()
    for name in SELECTED:
        data = (ROOT / 'supabase/migrations' / name).read_bytes()
        output = 'migrations/' + name
        (directory / output).write_bytes(data)
        hashes[output] = hashlib.sha256(data).hexdigest()
    manifest = {'project_ref': 'bxzwfidujuejmrbqjmgo', 'evidence_sha256': hashlib.sha256(EVIDENCE.read_bytes()).hexdigest(),
        'local_fixture_sha256': hashlib.sha256((directory / 'local-fixture.sql').read_bytes()).hexdigest(),
        'purpose': 'review only, no automatic execution', 'migration_files': hashes}
    (directory / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(directory)
    return directory


if __name__ == '__main__':
    prepare()
